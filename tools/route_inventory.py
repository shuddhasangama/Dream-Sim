"""Route inventory (c-security-suite).

    python tools/route_inventory.py           rewrite docs/ROUTE_INVENTORY.md
    python tools/route_inventory.py --check   exit 1 if it is out of date

Every route of the member app and the admin app with its access class. A new
route appears in the diff of this file, and test_security_suite.py checks every
class: public routes are listed here on purpose; every member API route answers
401 without sign-in; member routes never serve another member's objects; admin
routes require an admin session and, for owner routes, the owner role.
"""
import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
DOC = ROOT / 'docs' / 'ROUTE_INVENTORY.md'

# Member app: reachable without a member session, each for a stated reason.
PUBLIC = {
    'api_v1.health': 'liveness, no data',
    'api_v1.ready': 'readiness, no data',
    'auth_request': 'OTP request (rate limited, identical answers)',
    'auth_signup_request': 'signup OTP request (rate limited)',
    'auth_verify': 'OTP verification',
    'auth_refresh': 'refresh-token rotation',
    'auth_tester': 'tester sign-in, operator allow-list only',
    'auth_password_login': 'password sign-in (rate limited)',
    'static': 'static files',
}
SERVER_TO_SERVER = {
    '/billing/webhooks/razorpay': 'Razorpay webhook, raw-body HMAC',
    '/public/waitlist': 'public waitlist, origin allow-list + consent + rate limit',
}
# 404 whenever secure sign-in is on (simulation and local tools).
DISABLED_WITH_SIGN_IN = ('/pool', '/login/', '/admin', '/demo', '/verify/simulate', '/verify-contact')
# Routes removed on purpose. Each must answer 404 (test_security_suite.py).
RETIRED = {
    ('PUT', '/api/v1/profile/photo'): 'retired 2026-11-25: profile portrait upload (owner decision; the AI avatar replaces it)',
}
ADMIN_PUBLIC = {'/healthz', '/', '/robots.txt', '/api/login', '/static/<path:filename>'}
ADMIN_OWNER = {'/api/reports/markets', '/api/markets/readiness', '/api/reports/activities', '/api/activities/review',
               '/api/members/lock', '/api/members/unlock'}


def member_class(rule):
    if rule.endpoint in PUBLIC:
        return 'public', PUBLIC[rule.endpoint]
    if rule.rule in SERVER_TO_SERVER:
        return 'server-to-server', SERVER_TO_SERVER[rule.rule]
    if rule.endpoint == 'signzy_digilocker_callback':
        return 'server-to-server', 'sandbox acknowledgement only'
    if rule.rule == '/pool' or rule.rule.startswith(DISABLED_WITH_SIGN_IN):
        return 'disabled-with-sign-in', '404 when secure sign-in is on'
    if rule.rule.startswith('/api/v1/'):
        return 'member', 'bearer session; own objects only'
    return 'member-web', 'web session; redirects to sign-in'


def admin_class(rule):
    if rule.rule in ADMIN_PUBLIC:
        return 'public'
    if rule.rule in ADMIN_OWNER:
        return 'admin: owner'
    return 'admin: role section'


def methods(rule):
    return ','.join(sorted(m for m in rule.methods if m not in ('HEAD', 'OPTIONS')))


def member_rules():
    import app as member_app
    # '/__*' routes exist only inside tests and the e2e test server, never in the app.
    return sorted((r for r in member_app.app.url_map.iter_rules() if not r.rule.startswith('/__')),
                  key=lambda r: (r.rule, methods(r)))


def admin_rules():
    os.environ.setdefault('ADMIN_ALLOW_HTTP', '1')
    os.environ.setdefault('ADMIN_PUBLIC_ORIGIN', 'http://localhost')
    if not os.environ.get('ADMIN_TOTP_ENCRYPTION_KEY'):   # only to build the route map; no data is read
        from cryptography.fernet import Fernet
        os.environ['ADMIN_TOTP_ENCRYPTION_KEY'] = Fernet.generate_key().decode()
    from admin_dashboard.app import create_app
    return sorted(create_app().url_map.iter_rules(), key=lambda r: (r.rule, methods(r)))


def render():
    lines = ['# Route inventory', '',
             'Generated by `python tools/route_inventory.py`; checked by `test_security_suite.py`. '
             'Do not edit by hand.', '']
    members = member_rules()
    counts = {}
    for rule in members:
        counts[member_class(rule)[0]] = counts.get(member_class(rule)[0], 0) + 1
    lines += ['## Member app', '', 'Totals: ' + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())), '',
              '| Methods | Path | Access | Note |', '|---|---|---|---|']
    for rule in members:
        access, note = member_class(rule)
        lines.append(f'| {methods(rule)} | `{rule.rule}` | {access} | {note} |')
    lines += ['', '## Removed routes (answer 404)', '', '| Method | Path | Note |', '|---|---|---|']
    for (method, path), note in sorted(RETIRED.items()):
        lines.append(f'| {method} | `{path}` | {note} |')
    lines += ['', '## Admin app', '', '| Methods | Path | Access |', '|---|---|---|']
    for rule in admin_rules():
        lines.append(f'| {methods(rule)} | `{rule.rule}` | {admin_class(rule)} |')
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    fresh = render()
    if args.check:
        current = DOC.read_text(encoding='utf-8') if DOC.exists() else ''
        if current != fresh:
            print('docs/ROUTE_INVENTORY.md is out of date: run python tools/route_inventory.py')
            return 1
        print('Route inventory is up to date.')
        return 0
    DOC.write_text(fresh, encoding='utf-8')
    print(f'Wrote {DOC.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
