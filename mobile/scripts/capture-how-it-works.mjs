// Reproducible screenshots from the local preview only. No OTP/provider calls.
import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const mobile=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output=path.join(mobile, 'artifacts/how-it-works');
await mkdir(output,{recursive:true});
const server=spawn(process.execPath,[path.join(mobile,'node_modules/vite/bin/vite.js'),'--host','127.0.0.1','--port','5174','--strictPort'],{cwd:mobile,windowsHide:true,stdio:'ignore'});
let browser;
try {
  for(let i=0;i<100;i++) { try { if((await fetch('http://127.0.0.1:5174')).ok)break; } catch{} await new Promise(r=>setTimeout(r,100)); }
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2});
  await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:5174') ? route.continue() : route.abort());
  const shot=async(name,locator)=>{
    if(locator) await locator.evaluate(e=>scrollTo(0,scrollY+e.getBoundingClientRect().top-(document.querySelector('.chrome-sticky')?.offsetHeight||0)-18));
    else await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:path.join(output,`${name}.png`)});
    console.log(name);
  };
  await page.goto('http://127.0.0.1:5174');
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await shot('01-signup');
  await page.getByLabel('Phone number').fill('+15550001111');
  await page.getByRole('button',{name:'Send SMS code'}).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Your Vision',exact:true}).waitFor();
  await shot('02-vision',page.getByRole('heading',{name:"Where you're headed"}));
  await page.getByRole('button',{name:'Continue to Stats'}).click();
  await page.locator('#signup-stats').waitFor();
  await shot('03-stats',page.getByRole('heading',{name:'Your Stats'}));
  await page.getByRole('button',{name:'Continue to Chemistry'}).click();
  await page.locator('#activities-form').waitFor();
  await shot('04-chemistry',page.getByRole('heading',{name:"What you'd actually do together"}));
  await page.getByRole('button',{name:'Finish sign up'}).click();
  await page.getByRole('heading',{name:'Preview profile'}).waitFor();
  await shot('05-home');
  await page.locator('.topnav').getByRole('button',{name:'REACH',exact:true}).click();
  await page.locator('input[type=range]').first().waitFor();
  await shot('06-reach');
  await page.locator('.topnav').getByRole('button',{name:'Week',exact:true}).click();
  await page.locator('.the-week').waitFor();
  await shot('07-match1',page.locator('.candidate-card').first());
  await page.getByRole('button',{name:'+1 day',exact:true}).click();
  await page.locator('.tw-now').filter({hasText:'Tue 12:00'}).waitFor();
  await shot('08-match2',page.locator('.candidate-card').first());
  await page.getByRole('button',{name:'+1 day',exact:true}).click();
  await page.locator('.tw-now').filter({hasText:'Wed 12:00'}).waitFor();
  await shot('09-match3',page.locator('.the-week'));
  await page.getByRole('button',{name:'Express interest'}).click();
  await page.getByRole('button',{name:'Open calendar'}).click();
  await page.getByLabel('Fri · Dinner').check();
  await page.getByLabel('Sat · Dinner').check();
  await shot('10-slots',page.getByRole('heading',{name:'Your availability'}));
  await page.getByRole('button',{name:'Save availability'}).click();
  await page.getByRole('heading',{name:"You're both free"}).waitFor();
  await shot('11-overlap',page.getByRole('heading',{name:"You're both free"}));
  await page.getByRole('button',{name:'Confirm',exact:true}).first().click();
  await page.getByRole('button',{name:'View date plan'}).click();
  await page.getByRole('heading',{name:'Pending signatures'}).waitFor();
  await shot('12-plan');
  await page.getByRole('button',{name:'Review & sign'}).click();
  await page.getByRole('button',{name:"I've read this"}).click();
  await page.getByLabel('Your name').fill('Preview tester');
  await page.locator('input[name=ack]').evaluateAll(nodes=>nodes.forEach(n=>{n.checked=true;n.dispatchEvent(new Event('change',{bubbles:true}));}));
  await shot('13-agreement');
  await page.getByRole('button',{name:'Sign',exact:true}).click();
  await page.getByRole('button',{name:'Verify',exact:true}).click();
  await page.getByRole('button',{name:'After the date'}).click();
  await page.getByRole('heading',{name:'How did it go?'}).waitFor();
  await shot('14-debrief');
} finally { await browser?.close(); server.kill(); }
