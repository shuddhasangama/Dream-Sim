SELECT e.table_name, e.column_name,
       CASE WHEN t.table_name IS NULL THEN 'TABLE MISSING' ELSE 'COLUMN MISSING' END AS problem
FROM expected e
LEFT JOIN information_schema.columns c
  ON c.table_name = e.table_name AND c.column_name = e.column_name
 AND c.table_schema = 'public'
LEFT JOIN (SELECT DISTINCT table_name FROM information_schema.tables
           WHERE table_schema = 'public') t
  ON t.table_name = e.table_name
WHERE c.column_name IS NULL
ORDER BY 3, 1, 2;
