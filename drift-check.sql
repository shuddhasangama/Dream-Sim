--  drift-check.sql — what the deployed database is MISSING
--
--  WHY THIS EXISTS
--  init_db() runs CREATE TABLE IF NOT EXISTS on every request. On a table
--  that already exists that is a no-op — it does NOT add a column that was
--  added to the schema file later. So a new column ships in the code,
--  deploys cleanly, and then every write to that table fails with
--  'column "x" does not exist'.
--
--  Run this after any deploy that touched schema_postgres.sql. An empty
--  result means the live database matches the schema. Anything listed has
--  to be ALTERed in before the app can write to that table.
--
--  Read-only.
-- ═══════════════════════════════════════════════════════════════════════

